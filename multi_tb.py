path = kagglehub.dataset_download("usmanshams/tbx-11")
base_path = os.path.join(path, "TBX11K", "imgs")

print(os.listdir(base_path))

class_map = {
    "health": 0,
    "sick": 1,
    "tb": 2
}

image_paths = []
labels = []

for cls in ["health", "sick", "tb"]:
    folder = os.path.join(base_path, cls)
    for img in os.listdir(folder):
        image_paths.append(os.path.join(folder, img))
        labels.append(class_map[cls])

train_paths, val_paths, train_labels, val_labels = train_test_split(
    image_paths, labels, test_size=0.2, stratify=labels, random_state=42
)

class TBXDataset(Dataset):
    def __init__(self, paths, labels, transform=None):
        self.paths = paths
        self.labels = labels
        self.transform = transform

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, idx):
        image = Image.open(self.paths[idx]).convert("RGB")
        label = self.labels[idx]

        if self.transform:
            image = self.transform(image)

        return image, label

train_transform = transforms.Compose([
    transforms.Resize((224,224)),
    transforms.RandomHorizontalFlip(),
    transforms.RandomRotation(10),
    transforms.ColorJitter(0.2,0.2),
    transforms.ToTensor(),
    transforms.Normalize([0.485,0.456,0.406],
                         [0.229,0.224,0.225])
])

val_transform = transforms.Compose([
    transforms.Resize((224,224)),
    transforms.ToTensor(),
    transforms.Normalize([0.485,0.456,0.406],
                         [0.229,0.224,0.225])
])

train_dataset = TBXDataset(train_paths, train_labels, train_transform)
val_dataset = TBXDataset(val_paths, val_labels, val_transform)

train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True)
val_loader = DataLoader(val_dataset, batch_size=16)

class HybridCNNTransformer(nn.Module):
    def __init__(self, num_classes=3):
        super().__init__()

        self.backbone = timm.create_model(
            "resnet50",
            pretrained=True,
            num_classes=0
        )

        self.transformer = nn.TransformerEncoder(
            nn.TransformerEncoderLayer(
                d_model=2048,
                nhead=8,
                dim_feedforward=1024,
                dropout=0.3,
                batch_first=True
            ),
            num_layers=2
        )

        self.classifier = nn.Sequential(
            nn.Linear(2048, 512),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(512, num_classes)
        )

    def forward(self, x):
        x = self.backbone(x)       # (B, 2048)
        x = x.unsqueeze(1)         # (B, 1, 2048)
        x = self.transformer(x)
        return self.classifier(x[:, 0])

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = HybridCNNTransformer().to(device)

criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4)

train_loader = DataLoader(
    train_dataset,
    batch_size=16,
    shuffle=True,
    num_workers=2,      # IMPORTANT
    pin_memory=True
)

val_loader = DataLoader(
    val_dataset,
    batch_size=16,
    num_workers=2,
    pin_memory=True
)

def train_model(epochs=10):
    for epoch in range(epochs):
        model.train()
        total_loss = 0

        print(f"\n🚀 Epoch {epoch+1}/{epochs} started")

        for batch_idx, (x, y) in enumerate(train_loader):
            x, y = x.to(device), y.to(device)

            optimizer.zero_grad()
            preds = model(x)
            loss = criterion(preds, y)
            loss.backward()
            optimizer.step()

            total_loss += loss.item()

            if batch_idx % 10 == 0:
                print(f"  Batch {batch_idx} | Loss: {loss.item():.4f}")

        print(f"✅ Epoch {epoch+1} completed | Avg Loss: {total_loss/len(train_loader):.4f}")

for x, y in train_loader:
    x, y = x.to(device), y.to(device)
    out = model(x)
    print("Forward pass OK:", out.shape)
    break

train_model(epochs=10)

from sklearn.metrics import classification_report, confusion_matrix
